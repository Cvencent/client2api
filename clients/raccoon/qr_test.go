func rowsOf(m *qrMatrix) []string {
	out := make([]string, m.Size)
	for y := 0; y < m.Size; y++ {
		var b strings.Builder
		for x := 0; x < m.Size; x++ {
			if m.Modules[y][x] {
				b.WriteByte('1')
			} else {
				b.WriteByte('0')
			}
		}
		out[y] = b.String()
	}
	return out
}

func assertMatrix(t *testing.T, m *qrMatrix, want string) {
	t.Helper()
	wantRows := strings.Split(want, "\n")
	if m.Size != len(wantRows) {
		t.Fatalf("matrix size = %d, want %d", m.Size, len(wantRows))
	}
	got := rowsOf(m)
	for i := range wantRows {
		if got[i] != wantRows[i] {
			t.Fatalf("row %d mismatch\n got %s\nwant %s", i, got[i], wantRows[i])
		}
	}
}

func TestQRVersion1MatchesTheReferenceMatrix(t *testing.T) {
	m, err := qrBuildMatrix("hello")
	if err != nil {
		t.Fatalf("qrBuildMatrix: %v", err)
	}
	assertMatrix(t, m, qrVectorHello)
}

func TestQRVersion7MatchesTheReferenceMatrix(t *testing.T) {
	m, err := qrBuildMatrix(qrVectorURLInput)
	if err != nil {
		t.Fatalf("qrBuildMatrix: %v", err)
	}
	if m.Size != 49 {
		t.Fatalf("size = %d, want 49 (version 7)", m.Size)
	}
	assertMatrix(t, m, qrVectorURL)
}

func TestQROverCapacityIsAnError(t *testing.T) {
	if _, err := qrBuildMatrix(strings.Repeat("x", 214)); err == nil {
		t.Fatal("a 214-byte payload produced a matrix, want an error")
	}
	// 213 bytes is exactly the version-10 limit and must still work.
	if _, err := qrBuildMatrix(strings.Repeat("x", 213)); err != nil {
		t.Fatalf("a 213-byte payload failed: %v", err)
	}
}

func TestQRCountsBytesNotRunes(t *testing.T) {
	// 71 three-byte characters are 213 bytes: at the limit, not over it.
	if _, err := qrBuildMatrix(strings.Repeat("熊", 71)); err != nil {
		t.Fatalf("213 bytes of UTF-8 failed: %v", err)
	}
	if _, err := qrBuildMatrix(strings.Repeat("熊", 72)); err == nil {
		t.Fatal("216 bytes of UTF-8 produced a matrix, want an error")
	}
}

func TestQRFunctionPatternsAreWellFormed(t *testing.T) {
	m, err := qrBuildMatrix("hello")
	if err != nil {
		t.Fatalf("qrBuildMatrix: %v", err)
	}
	dark := func(x, y int) bool { return m.Modules[y][x] }
	if !dark(0, 0) || !dark(6, 0) || dark(7, 0) || dark(0, 7) {
		t.Fatal("the top-left finder and its separator are malformed")
	}
	if !dark(6, 8) || dark(6, 9) {
		t.Fatal("the horizontal timing pattern is malformed")
	}
	if !dark(8, 6) || dark(9, 6) {
		t.Fatal("the vertical timing pattern is malformed")
	}
	if !dark(8, m.Size-8) {
		t.Fatal("the fixed dark module is missing")
	}
}

