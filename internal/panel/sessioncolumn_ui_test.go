package panel

import (
	"strings"
	"testing"
)

// ---------------------------------------------------------------------------
// 「最近调用」会话ID 那一列的显示。
//
// 修复之后这一列基本不会再空：调用方报了会话就显示它，没报就用网关从消息内容
// 推出来的键（带 core.DerivedKeyPrefix 的 "d-" 前缀）。两种来源长得不一样是故意
// 的 —— "调用方报的会话"和"网关推出来的会话"可信度不同，操作员看到一列 d- 开头的
// 值，就该知道那是推出来的，不是客户端真的声明了这次对话。
//
// 但前缀不能直接甩在脸上让人猜：表头要说明这列是什么，悬停要说明值从哪来，
// 空值也要说明"连内容都推不出来"，而不是一个没有解释的破折号。
// ---------------------------------------------------------------------------

func TestSessionIDColumnExplainsDerivedAndEmptyValues(t *testing.T) {
	src := poolStatsUISource(t)

	// 1. 表头说清这一列的来历。
	if !strings.Contains(src, "调用方报的就原样显示") {
		t.Error("会话ID 表头没有说明这一列的值从哪来")
	}

	// 2. 渲染函数必须把 d- 前缀当成"推导出来的"讲，而不是当成普通 id 显示。
	if !strings.Contains(src, "网关按消息内容推导") {
		t.Error("会话ID 单元格没有区分「调用方报的」和「网关推导的」")
	}

	// 3. 空值仍然可达，但必须解释为什么空。
	if !strings.Contains(src, "无会话标识") {
		t.Error("空会话ID 直接显示一个破折号，操作员不知道是调用方没报还是内容推不出来")
	}

	// 4. 去掉 d- 前缀后显示，避免长 hex 撑破列宽。
	if !strings.Contains(src, `s.startsWith("d-")`) {
		t.Error("d- 前缀应该只在 title 里保留，列里显示去掉前缀的短值")
	}
}
